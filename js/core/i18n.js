let lang = (() => {
  try {
    const saved = localStorage.getItem('mp2:lang');
    if (saved === 'ru' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return (navigator.language || 'ru').toLowerCase().startsWith('ru') ? 'ru' : 'en';
})();

export function getLang() {
  return lang;
}

export function t(key, vars = null) {
  let text = dict[lang]?.[key] ?? dict.ru[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function hasKey(key) {
  return Boolean(dict[lang]?.[key] ?? dict.ru[key]);
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (!hasKey(key)) return;
    // Сохраняем вложенные элементы (например <strong id="speedValue">)
    const keep = node.querySelector('strong, b');
    if (keep) {
      node.textContent = '';
      node.append(t(key) + ' ', keep);
    } else {
      node.textContent = t(key);
    }
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.title = t(node.dataset.i18nTitle);
  });
  document.querySelectorAll('#langToggle, #entryLangBtn').forEach((btn) => {
    btn.textContent = lang === 'ru' ? 'EN' : 'RU';
  });
}

export function setLang(next) {
  if (next !== 'ru' && next !== 'en') return;
  lang = next;
  try { localStorage.setItem('mp2:lang', lang); } catch { /* ignore */ }
  applyI18n();
  emit('lang', lang);
}

export function toggleLang() {
  setLang(lang === 'ru' ? 'en' : 'ru');
}
